//! Fixture-owned Wire identities and budgets shared by both RPC ends.

pub const LIMITS: ic_wire::Limits = ic_wire::Limits {
    bytes: 64 * 1024,
    allocation: 1024 * 1024,
    nodes: 16 * 1024,
    depth: 32,
};
#[derive(Clone, Copy)]
#[repr(u64)]
pub enum Method {
    Initialize = 4096,
    AfterUpgrade = 4097,
    Value = 4098,
    Scalar = 4099,
    Tuple = 4100,
    Unit = 4101,
    Awaited = 4102,
    Composite = 4103,
    Guarded = 4104,
    Manual = 4105,
    CallbackTrap = 4106,
    Cleaned = 4107,
    ProtectedPending = 4108,
    Migratory = 4109,
    Controller = 4110,
    Missing = 4111,
    CycleReceiver = 4112,
    CycleTotal = 4113,
    CycleRoundtrip = 4114,
    Checkpoint = 4115,
    StableEdit = 4116,
    StableValue = 4117,
    CheckpointBytes = 4118,
    PublishRoot = 4119,
    Certificate = 4120,
    SystemHelpers = 4121,
    ExternalManagement = 4122,
    TimerStart = 4123,
    SubmissionPressure = 0x2000,
    InsufficientCycles = 0x2001,
    WeakPending = 0x2002,
    BufferCopy = 0x2003,
    SelfWakeQuery = 0x2004,
    ManagementProof = 0x2005,
    Absent = 0xffff,
}
pub fn method_id(name: &str) -> u64 {
    match name {
        "initialize" => Method::Initialize as u64,
        "after_upgrade" => Method::AfterUpgrade as u64,
        "value" => Method::Value as u64,
        "scalar" => Method::Scalar as u64,
        "tuple" => Method::Tuple as u64,
        "unit" => Method::Unit as u64,
        "awaited" => Method::Awaited as u64,
        "composite" => Method::Composite as u64,
        "guarded" => Method::Guarded as u64,
        "manual" => Method::Manual as u64,
        "callback_trap" => Method::CallbackTrap as u64,
        "cleaned" => Method::Cleaned as u64,
        "protected_pending" => Method::ProtectedPending as u64,
        "migratory" => Method::Migratory as u64,
        "controller" => Method::Controller as u64,
        "missing" => Method::Missing as u64,
        "cycle_receiver" => Method::CycleReceiver as u64,
        "cycle_total" => Method::CycleTotal as u64,
        "cycle_roundtrip" => Method::CycleRoundtrip as u64,
        "checkpoint" => Method::Checkpoint as u64,
        "stable_edit" => Method::StableEdit as u64,
        "stable_value" => Method::StableValue as u64,
        "checkpoint_bytes" => Method::CheckpointBytes as u64,
        "publish_root" => Method::PublishRoot as u64,
        "certificate" => Method::Certificate as u64,
        "system_helpers" => Method::SystemHelpers as u64,
        "external_management" => Method::ExternalManagement as u64,
        "timer_start" => Method::TimerStart as u64,
        "submission_pressure" => Method::SubmissionPressure as u64,
        "insufficient_cycles" => Method::InsufficientCycles as u64,
        "weak_pending" => Method::WeakPending as u64,
        "buffer_copy" => Method::BufferCopy as u64,
        "self_wake_query" => Method::SelfWakeQuery as u64,
        "management_proof" => Method::ManagementProof as u64,
        "no_such_method" => Method::Absent as u64,
        _ => panic!("unknown fixture endpoint: {name}"),
    }
}
